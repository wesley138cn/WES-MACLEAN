#!/usr/bin/env python3
"""Generate ignored, machine-local signing configuration. Never exports keys."""
import os
import plistlib
import re
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sha = os.environ.get('MACLEAN_SIGNING_IDENTITY', '').upper()
if sha:
    if not re.fullmatch(r'[0-9A-F]{40}', sha):
        raise SystemExit('MACLEAN_SIGNING_IDENTITY must be a certificate SHA-1 fingerprint')
    identities = subprocess.check_output(['security', 'find-identity', '-v', '-p', 'codesigning'], text=True)
    if sha not in identities:
        raise SystemExit('Signing identity unavailable in the current keychain')
else:
    sha = '0' * 40
label = 'local.wesp.MacleanHelper'
rule = f'anchor apple generic and identifier "local.wesp.Lime" and certificate leaf = H"{sha}"'
(root / 'Sources/MacleanShared/SignerIdentity.swift').write_text(
    '// Generated by scripts/configure.py; excluded from source control.\n'
    'public enum SignerIdentity {\n'
    f'    public static let sha1 = "{sha}"\n'
    '}\n')
(root / 'HelperSupport/Info.plist').write_bytes(plistlib.dumps({
    'CFBundleIdentifier': label, 'CFBundleName': 'WES·MACLEAN 清理助手',
    'CFBundleVersion': '1', 'CFBundleShortVersionString': '1.0.0',
    'SMAuthorizedClients': [rule]}))
print('Configured Apple-signed build' if sha != '0' * 40 else 'Configured local development build (helper disabled)')
